/** Identify a human input boundary without reading any attachment payload. */
export function userInput(data) {
  const message = data?.message;
  const sources = [data?.source, message?.source].filter(source => source != null);
  if (sources.some(source => source.kind !== 'user')
    || [data?.role, message?.role].some(role => role != null && role !== 'user')) return null;
  const blocks = message?.content ?? data?.content;
  if (!Array.isArray(blocks)) return null;
  const hasAttachments = blocks.some(b => b?.type === 'image' || b?.type === 'file');
  const raw = blocks.filter(b => b?.type === 'text' && typeof b.text === 'string').map(b => b.text).join('\n');
  // Explicitly authored text stays literal, including examples of runtime headers.
  const text = raw.trim() ? (sources.length ? raw : legacyWords(raw)) : null;
  return text !== null || hasAttachments ? {text,hasAttachments} : null;
}

function legacyWords(text) {
  if (/^\[model changed: assistant turns above this point were generated by [^\n]+; the session continues with [^\n]+\]$/.test(text)) return null;
  if (text === 'Current runtime context: none. Earlier runtime-context snapshots no longer apply.') return null;
  if (!/^Current runtime context\.(?:\r?\n|$)/.test(text)) return text;
  // Older hosts put a well-known preamble ahead of the user's words. Only
  // strip consecutive header lines; do not filter lines inside the actual message.
  const lines = text.split(/\r?\n/);
  let i = 1;
  while (i < lines.length && (!lines[i].trim() || /^(?:Current working directory:|Current DSH file policy:|Current DeepSeek Harness|Approval prompts are disabled|Time sampled while preparing|Browser time zone for this request:|Elapsed since the preceding|You are (?:the Team Lead|an AI agent)\b|Use list_agents\(\{\}\) to find your teammates\b)/.test(lines[i]))) i++;
  return lines.slice(i).join('\n') || null;
}
